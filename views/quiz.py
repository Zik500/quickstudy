from actions.sync_data import report, submit_quiz
from config import DIFFICULTIES, QUESTION_COUNTS, QUIZ_SOURCES
from services.secrets import get_secret
from ui.components import (answer_pill, audio_tutor, language_selector, page_header, require_library,
                           run_quiz_with_status, start_revision_quiz, status_badge, topic_pills, topic_tags)
from utils.text import friendly_error


def show_quiz_setup():
    """Choose chapters, page ranges, number of questions and difficulty."""
    library = st.session_state.library
    with st.container(key="card_quiz_setup"):
        st.multiselect(
            "Choose chapters",
            list(library),
            key="quiz_files",
            persist_state="session",
            placeholder="Choose one or more PDFs",
        )
        st.radio(
            "Quiz source",
            QUIZ_SOURCES,
            key="quiz_source",
            horizontal=True,
            persist_state="session",
            help="Study notes are short, so the quiz is much faster. Full PDF uses all the details.",
        )

        # Optional page range for each chosen chapter (only for the full PDF)
        if st.session_state.quiz_source == QUIZ_SOURCES[1]:
            for file_id in st.session_state.quiz_files:
                pages = library[file_id]["num_pages"]
                if pages > 1:
                    st.session_state.setdefault(f"pages_{file_id}", (1, pages))
                    st.slider(
                        f"Pages of {library[file_id]['name']}",
                        min_value=1,
                        max_value=pages,
                        key=f"pages_{file_id}",
                        persist_state="session",
                    )
        else:
            st.caption("Uses the study notes of each chapter (they are created first if needed).")

        count_col, level_col = st.columns(2)
        with count_col:
            st.segmented_control(
                "Number of questions", QUESTION_COUNTS, key="quiz_count", required=True, persist_state="session"
            )
        with level_col:
            st.segmented_control(
                "Difficulty", DIFFICULTIES, key="quiz_difficulty", required=True, persist_state="session"
            )

        chosen = st.session_state.quiz_files
        with st.container(horizontal=True, gap="small"):
            generate = st.button("Generate Quiz", type="primary", disabled=not chosen)
            # Same settings again = the saved quiz; this button always asks for new questions
            new_questions = st.button("New questions", icon=":material/refresh:", disabled=not chosen)
        if generate or new_questions:
            run_quiz_with_status(
                lambda progress: generate_quiz(chosen, "Regular", use_cache=not new_questions, progress=progress)
            )
        if not chosen:
            st.caption("Choose at least one chapter.")


def render():
    page_header("Quiz", "Questions based only on the chapters you choose.")
    if not require_library():
        return
    if not get_secret("GEMINI_API_KEY") and not get_secret("GROQ_API_KEY"):
        st.error("Add GEMINI_API_KEY or GROQ_API_KEY to .streamlit/secrets.toml to use the quiz.")
        return

    if st.session_state.pop("revision_ready", False):
        st.success("Your revision quiz is ready. Good luck!")

    show_quiz_setup()

    questions = st.session_state.quiz
    if not questions:
        return

    number = st.session_state.quiz_number
    st.markdown(
        f'<div class="qs-label">Quiz {number} · {st.session_state.quiz_type} · {st.session_state.quiz_level}</div>',
        unsafe_allow_html=True,
    )
    st.caption(
        f"Chapters: {', '.join(st.session_state.quiz_chapters)} · "
        f"Generated by: {st.session_state.quiz_generator} in {st.session_state.quiz_seconds:.1f} seconds"
    )

    # A form collects all answers, so the page does not rerun on every click
    with st.form(f"quiz_form_{number}", border=False):
        choices = []
        for i, q in enumerate(questions):
            with st.container(key=f"card_question_{number}_{i}"):
                st.markdown(topic_tags(q), unsafe_allow_html=True)
                st.markdown(f"**Q{i + 1}. {q['question']}**")
                choice = st.radio(
                    f"Answer for question {i + 1}",
                    options=range(4),
                    format_func=lambda idx, q=q: q["options"][idx],
                    index=None,
                    key=f"answer_{number}_{i}",
                    label_visibility="collapsed",
                    disabled=st.session_state.submitted,
                )
            choices.append(choice)
        submitted = st.form_submit_button("Submit", type="primary", disabled=st.session_state.submitted)

    if submitted:
        if None in choices:
            st.warning("Please answer every question before submitting.")
        else:
            st.session_state.answers = choices
            st.session_state.submitted = True
            submit_quiz(questions, choices)  # session + Supabase
            st.rerun()

    if st.session_state.submitted:
        show_results(questions)


def show_results(questions: list[dict]):
    """Score, "You are weak in" card and one card per question.
    Shown immediately after Submit: no AI call until the student clicks "Explain more"."""
    answers = st.session_state.answers
    score = sum(a == q["correct_index"] for a, q in zip(answers, questions))
    number = st.session_state.quiz_number

    with st.container(key=f"card_score_{number}"):
        st.markdown(f'<div class="qs-page-title">Score: {score}/{len(questions)}</div>', unsafe_allow_html=True)
        st.progress(score / len(questions))

    # Highlighted card: short topic names answered wrong in THIS quiz (reported questions excluded)
    wrong = [i for i, (q, a) in enumerate(zip(questions, answers))
             if a != q["correct_index"] and i not in st.session_state.reported]
    topics, keys = [], []
    for i in wrong:
        if questions[i]["topic_key"] not in keys:
            keys.append(questions[i]["topic_key"])
            topics.append(questions[i]["topic"])
    if wrong:
        with st.container(key=f"card_alert_quiz_{number}"):
            st.markdown("**You are weak in:**")
            st.markdown(topic_pills(topics), unsafe_allow_html=True)
            if st.button("Revise these topics now", type="primary", icon=":material/autorenew:",
                         key=f"revise_now_{number}"):
                start_revision_quiz(keys)

    if score < len(questions):
        st.markdown('<div class="qs-label">Audio Tutor language</div>', unsafe_allow_html=True)
        language_selector("quiz")

    st.markdown('<div class="qs-label">Your answers</div>', unsafe_allow_html=True)
    for i, (q, answer) in enumerate(zip(questions, answers)):
        if answer == q["correct_index"]:
            correct_card(number, i, q)
        else:
            wrong_card(number, i, q, answer)


def report_button(number: int, index: int):
    """"⚑ Report question": the question is marked in history and not counted as a weak topic."""
    reported = index in st.session_state.reported
    st.button("⚑ Reported" if reported else "⚑ Report question", key=f"report_{number}_{index}",
              type="tertiary", disabled=reported, on_click=report, args=(index,))


def correct_card(number: int, index: int, q: dict):
    """A correct answer: a compact green card, collapsed by default."""
    with st.container(key=f"card_correct_{number}_{index}"):
        with st.expander(f"Q{index + 1} · :green[✓ Correct] · {q['topic']}", expanded=False):
            st.markdown(topic_tags(q), unsafe_allow_html=True)
            st.markdown(f"**{q['question']}**")
            st.markdown(answer_pill(q["answer"], correct=True), unsafe_allow_html=True)
            st.markdown(f"💡 {q['explanation']}")
            report_button(number, index)


def wrong_card(number: int, index: int, q: dict, answer: int):
    """A wrong answer: badges, answer pills, explanation, quote and a small action row."""
    detailed = st.session_state.explanations.get(index)
    explanation = detailed["explanation"] if detailed else q["explanation"]

    with st.container(key=f"card_wrong_{number}_{index}"):
        st.markdown(
            f'<div class="qs-result-head"><span class="qs-qnum">Q{index + 1}</span>{status_badge(False)}'
            f'{topic_tags(q)}</div>',
            unsafe_allow_html=True,
        )
        st.markdown(f"**{q['question']}**")
        st.markdown(answer_pill(q["options"][answer], correct=False) + answer_pill(q["answer"], correct=True),
                    unsafe_allow_html=True)
        st.markdown(f"💡 {html.escape(explanation)}")
        if detailed and detailed["quote"]:
            with st.expander("📖 From your notes"):
                st.markdown(f"> {detailed['quote']}")
        if detailed:
            st.caption(f"Generated by: {detailed['generated_by']}")
        if index in st.session_state.reported:
            st.caption("⚑ You reported this question, so it does not count as a weak topic.")

        # Small grey action row: Listen · Explain more · Report question
        with st.container(horizontal=True, gap="small", key=f"actions_q_{number}_{index}"):
            listen = st.button("🔊 Listen", key=f"listen_q_{number}_{index}", type="tertiary")
            more = st.button("Explain more", key=f"more_{number}_{index}", type="tertiary",
                             disabled=detailed is not None)
            report_button(number, index)

        # "Explain more": only now ask the AI (main Groq model), then keep the result
        if more:
            with st.spinner("Writing a detailed explanation..."):
                try:
                    st.session_state.explanations[index] = explain_more(st.session_state.quiz_text, q, answer)
                except Exception as e:
                    friendly_error(e)  # logs the details in the terminal
                    st.info("AI is busy right now. Showing the basic explanation instead.")
            if index in st.session_state.explanations:
                st.rerun()  # redraw the card with the detailed explanation

        # "Listen": the Audio Tutor explains this mistake out loud (detailed or short explanation)
        if listen:
            st.session_state[f"play_mistake_{number}_{index}"] = True
        if st.session_state.get(f"play_mistake_{number}_{index}"):
            audio_tutor(
                "Explain this to me (Audio)",
                f"mistake_{number}_{index}",
                lambda language, q=q, answer=answer, text=explanation:
                    tutor_script_for_mistake(q, answer, text, language),
                auto=True,
            )
