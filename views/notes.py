"""Notes page: upload PDFs, chapter outline and study notes."""

import html

import streamlit as st

from actions.generate_notes import generate_study_notes
from actions.generate_outline import make_outline
from actions.sync_data import save_notes
from config import MAX_GROQ_CHARS
from state import go_to, log_activity
from ui.components import chapter_list, language_selector, notes_selector, page_header, upload_card
from utils.text import friendly_error


def show_outline(file_id: str):
    """Show the chapter outline (made once by Groq when the PDF was added)."""
    info = st.session_state.library[file_id]
    with st.container(key="card_outline"):
        st.markdown("**Chapter outline**")
        if info.get("text_source") == "Gemini Vision":
            st.caption("Text extracted by: Gemini Vision (this PDF looks scanned)")
        if info.get("outline"):
            for number, section in enumerate(info["outline"], start=1):
                st.markdown(f"{number}. **{section['title']}** – {section['description']}")
        else:
            st.caption(info.get("outline_error") or "No outline yet.")
            if st.button("Try again", icon=":material/refresh:", key=f"outline_retry_{file_id}"):
                with st.spinner("Making an outline..."):
                    make_outline(file_id)
                st.rerun()


def render():
    page_header("Study Notes", "Upload your chapters, then get an outline and study notes for each one.")

    # The ONLY place to upload: drag & drop card + the list of chapters
    with st.container(key="card_upload"):
        st.markdown("**My Notes Library**")
        upload_card("notes")
        chapter_list()
    if not st.session_state.library:
        return

    file_col, lang_col = st.columns([2, 1], vertical_alignment="bottom")
    with file_col:
        notes_selector()
    with lang_col:
        language_selector("notes")

    file_id = st.session_state.current_file
    language = st.session_state.tutor_language
    info = st.session_state.library[file_id]
    cache_key = f"{file_id}|{language}"

    show_outline(file_id)

    # Notes are cached per file and per language
    if cache_key not in st.session_state.notes_cache:
        with st.container(key="card_notes_start"):
            st.markdown(f"Turn **{html.escape(info['name'])}** into short study notes in {language}.")
            if st.button("Generate Study Notes", type="primary"):
                with st.spinner("Writing your study notes..."):
                    try:
                        notes = generate_study_notes(info["text"], language)
                        st.session_state.notes_cache[cache_key] = notes
                        save_notes(file_id, language, notes)
                    except Exception as e:
                        st.error(f"Could not generate study notes. {friendly_error(e)}")
        if cache_key not in st.session_state.notes_cache:
            return

    notes = st.session_state.notes_cache[cache_key]
    log_activity("notes", "", file_id)  # for "Continue where you left off"
    if notes["error"]:
        st.warning(
            "Groq was not available, so a simpler local summary was used. "
            f"Reason: {friendly_error(Exception(notes['error']))}"
        )
    with st.container(key="card_notes"):
        if len(info["text"]) > MAX_GROQ_CHARS and notes["source"].startswith("Groq"):
            st.caption(f"Only the first {MAX_GROQ_CHARS:,} characters of this PDF were sent to Groq.")
        st.markdown(notes["markdown"])
        st.caption(f"Generated by: {notes['source']}")
    st.button(
        "Explain these notes with the Audio Tutor",
        icon=":material/headphones:",
        on_click=go_to,
        args=("Audio Tutor",),
    )
