"""AI router: every task goes to Groq first; if Groq fails, Gemini answers instead.

Groq fails over to Gemini on any error: 429 rate limit, 5xx, a timeout (~20 s),
or a reply that is not the JSON we asked for. The returned label says which AI
answered, for the small "Generated by: ..." text in the app.
"""

import json

from config import GROQ_MAIN
from services.gemini_client import gemini_generate
from services.groq_client import groq_chat
from utils.text import parse_json

GEMINI_LABEL = "Gemini (backup)"


def groq_label(model: str) -> str:
    """'Groq (openai/gpt-oss-120b)' etc."""
    return f"Groq ({model})"


def with_schema_hint(messages: list[dict], schema) -> list[dict]:
    """Add the JSON schema to the system message, so the model knows the exact format."""
    hint = "Reply ONLY with JSON that matches this JSON schema:\n" + json.dumps(schema.model_json_schema())
    if messages and messages[0]["role"] == "system":
        return [{"role": "system", "content": messages[0]["content"] + "\n\n" + hint}] + messages[1:]
    return [{"role": "system", "content": hint}] + messages


def ask_ai(messages: list[dict], max_tokens: int, model: str = GROQ_MAIN, json_mode: bool = False,
           reasoning_effort: str = "low", backup_messages: list[dict] = None) -> tuple[str, str]:
    """Ask Groq; if it fails, ask Gemini with the same prompt.

    backup_messages can give Gemini a longer version of the prompt (it accepts more text).
    Returns (reply text, label of the AI that answered). Raises the Groq error if both fail.
    """
    try:
        return groq_chat(messages, max_tokens, json_mode, model, reasoning_effort), groq_label(model)
    except Exception as groq_error:
        print(f"[QuickStudy] Groq failed, trying Gemini: {groq_error!r}")
        try:
            return gemini_generate(backup_messages or messages, max_tokens + 1000, json_mode), GEMINI_LABEL
        except Exception as gemini_error:
            print(f"[QuickStudy] Gemini backup failed too: {gemini_error!r}")
            raise groq_error


def ask_ai_json(messages: list[dict], max_tokens: int, schema=None, model: str = GROQ_MAIN,
                reasoning_effort: str = "low", backup_messages: list[dict] = None):
    """Like ask_ai, but the reply must be valid JSON (and match the pydantic schema, if given).

    A Groq reply that is not valid JSON also goes to Gemini.
    Returns (dict or schema object, label of the AI that answered).
    """
    def parse(raw: str):
        data = parse_json(raw)
        return schema.model_validate(data) if schema else data

    groq_messages = with_schema_hint(messages, schema) if schema else messages
    try:
        raw = groq_chat(groq_messages, max_tokens, True, model, reasoning_effort)
        return parse(raw), groq_label(model)
    except Exception as groq_error:
        print(f"[QuickStudy] Groq failed, trying Gemini: {groq_error!r}")
        try:
            raw = gemini_generate(backup_messages or messages, max_tokens + 1000, json_mode=True, schema=schema)
            return parse(raw), GEMINI_LABEL
        except Exception as gemini_error:
            print(f"[QuickStudy] Gemini backup failed too: {gemini_error!r}")
            raise groq_error
